// Genera src/core/api/schema.d.ts a partir de la copia api/openapi.json (no necesita la API).
// Uso: npm run api:types
import { writeFile } from 'node:fs/promises';

import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const NUMBER = ts.factory.createKeywordTypeNode(ts.SyntaxKind.NumberKeyword);
const NULL = ts.factory.createLiteralTypeNode(ts.factory.createNull());

// ASP.NET Core acepta números como texto al LEER peticiones (AllowReadingFromString), y por eso el contrato los
// declara "number | string". Las respuestas siempre traen números, así que se tipan como number.
// Importante: la app nunca hace aritmética con dinero (los floats de JS no son decimales); solo lo muestra.
function isNumberOrNumericString(schema) {
  const types = Array.isArray(schema.type) ? schema.type : [];
  return types.includes('number') || types.includes('integer')
    ? types.includes('string') && typeof schema.pattern === 'string'
    : false;
}

const ast = await openapiTS(new URL('../api/openapi.json', import.meta.url), {
  transform(schema) {
    if (!isNumberOrNumericString(schema)) {
      return undefined;
    }
    return schema.type.includes('null') ? ts.factory.createUnionTypeNode([NUMBER, NULL]) : NUMBER;
  },
});

const header = '// Generated by `npm run api:types` from api/openapi.json. Do not edit by hand.\n';
await writeFile(new URL('../src/core/api/schema.d.ts', import.meta.url), header + astToString(ast), 'utf8');
process.stdout.write('Generated src/core/api/schema.d.ts\n');
